export function getFormulasBySubject(subjectId: string): FormulaEntry[] {
  return FORMULAS.filter((f) => f.subjectId === subjectId);
}

export function getFormulaCategories(subjectId?: string): string[] {
  const pool = subjectId ? getFormulasBySubject(subjectId) : FORMULAS;
  return Array.from(new Set(pool.map((f) => f.category)));
}
